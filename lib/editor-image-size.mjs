export const MIN_IMAGE_WIDTH = 96;
export const MAX_IMAGE_WIDTH = 1200;

const PREFIX = "MBSK_IMAGE_V1:";
const encoder = new TextEncoder();
const decoder = new TextDecoder("utf-8", { fatal: true });

export function imageWidth(value) {
  if (value === null || value === undefined || value === "") return null;
  const number = Number(value);
  return Number.isFinite(number)
    ? Math.min(MAX_IMAGE_WIDTH, Math.max(MIN_IMAGE_WIDTH, Math.round(number)))
    : null;
}

function encode(value) {
  const bytes = encoder.encode(value);
  let binary = "";
  for (const byte of bytes) binary += String.fromCharCode(byte);
  return btoa(binary)
    .replace(/\+/g, "-")
    .replace(/\//g, "_")
    .replace(/=+$/, "");
}

function decode(value) {
  if (!/^[A-Za-z0-9_-]*$/.test(value) || value.length % 4 === 1) return null;
  try {
    const binary = atob(value.replace(/-/g, "+").replace(/_/g, "/"));
    const bytes = Uint8Array.from(binary, (character) =>
      character.charCodeAt(0),
    );
    const result = decoder.decode(bytes);
    return encode(result) === value ? result : null;
  } catch {
    return null;
  }
}

// An existing title exactly matching either grammar is an unavoidable in-band collision.
// Titles generated by this app are escaped before they can become such a collision.
export function decodeImageTitle(title) {
  if (typeof title !== "string")
    return { title: null, width: null, encoded: false };
  const sized =
    /^MBSK_IMAGE_V1:(96|9[7-9]|[1-9][0-9]{2}|1[01][0-9]{2}|1200):([A-Za-z0-9_-]*)$/.exec(
      title,
    );
  if (sized) {
    const original = decode(sized[2]);
    if (original !== null)
      return { title: original, width: Number(sized[1]), encoded: true };
  }
  const literal = /^MBSK_IMAGE_V1:literal:([A-Za-z0-9_-]*)$/.exec(title);
  if (literal) {
    const original = decode(literal[1]);
    if (original !== null)
      return { title: original, width: null, encoded: true };
  }
  return { title, width: null, encoded: false };
}

export function encodeImageTitle(title, width) {
  const original = typeof title === "string" ? title : "";
  const bounded = imageWidth(width);
  if (bounded !== null) return `${PREFIX}${bounded}:${encode(original)}`;
  return decodeImageTitle(original).encoded
    ? `${PREFIX}literal:${encode(original)}`
    : original;
}
